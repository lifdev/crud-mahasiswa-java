    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String nama,nim,jk,jurusan,hp,alamat;
        nim = nimTxt.getText();
        nama = namaTxt.getText();
        jk = "";
        if(jk1.isSelected()){
            jk = jk1.getText();
        }else{
            jk = jk2.getText();
        }
        
        jurusan = (String) jurCB.getSelectedItem();
        hp = hpTxt.getText();
        alamat = alamatTxt.getText();
        
        if(nim.equals("")){
            JOptionPane.showMessageDialog(null, "Nim Tidak Boleh Kosong");
        }else{
            try{
                st = cn.createStatement();
                String SQL = "update tb_mahasiswa set nama='"+nama+"', jk='"+jk+"', prodi='"+jurusan+"', no_hp='"+ hp+"', alamat='"+ alamat+"' where nim='"+nim+"'";
                st.executeUpdate(SQL);
                tampilData();
                reset();
                JOptionPane.showMessageDialog(null, "Data berhasil diupdate");
            }catch(Exception e){
                JOptionPane.showMessageDialog(null, "Data gagal diupdate");    
            }
        }
       
    }//GEN-LAST:event_jButton2ActionPerformed


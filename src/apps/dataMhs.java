    private void tableMhsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMhsMouseClicked
        // TODO add your handling code here:
        try{
            int row = tableMhs.getSelectedRow();
            String pilih = (tableMhs.getModel().getValueAt(row, 0).toString());
            st = cn.createStatement();
            rs = st.executeQuery("select * from tb_mahasiswa where nim='"+pilih+"'");
            
            if(rs.next()) {
                String nim = rs.getString("nim");
                String nama = rs.getString("nama");
                String jk = rs.getString("jk");
                String prodi = rs.getString("prodi");
                String hp = rs.getString("no_hp");
                String alamat = rs.getString("alamat");
                
                nimTxt.setText(nim);
                namaTxt.setText(nama);
                hpTxt.setText(hp);
                alamatTxt.setText(alamat);
                
                if("Laki-laki".equals(jk)) {
                   jk1.setSelected(true);
                }else if("Perempuan".equals(jk)){
                    jk2.setSelected(true);
                }
                
                jurCB.setSelectedItem(prodi);
            }else{
                
            }
        }catch(Exception e){
            System.out.print(e);
        }
    }//GEN-LAST:event_tableMhsMouseClicked

    public void cariData(String keyboard){
        try{
            String query = "SELECT * FROM tb_mahasiswa where nim like ? or nama like ? or jk like ? or prodi like ? or no_hp like ? or alamat like ?";
            PreparedStatement ps  = cn.prepareStatement(query);
            String cari = "%" + keyboard + "%";
            ps.setString(1, cari);
            ps.setString(2, cari);
            ps.setString(3, cari);
            ps.setString(4, cari);
            ps.setString(5, cari);
            ps.setString(6, cari);
            rs = ps.executeQuery();
            
            tabModel.getDataVector().removeAllElements();
            tabModel.fireTableDataChanged();
            
            while(rs.next()){
                Object[] data= {
                    rs.getString("nim"),
                    rs.getString("nama"),
                    rs.getString("jk"),
                    rs.getString("prodi"),
                    rs.getString("no_hp"),
                    rs.getString("alamat"),
                };
                tabModel.addRow(data);
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, e);
        }
    } 
    
